# 运行结束后，请直接打开数据存储器，核对以下地址的数据是否完全一致：
#
#  RAM地址  | 对应指令 | 预期十六进制值 (32-bit HEX) | 验证的中间核心逻辑
# ----------|----------|-----------------------------|------------------------
#  0x000000 |  初始加载| 0x12345678                  | 原始RAM数据（未被破坏）
#  0x000004 |  初始加载| 0xABCDEF01                  | 原始RAM数据（未被破坏）
#  0x000008 |  addiu   | 0x0000000A                  | 寄存器初始化正数
#  0x00000C |  addiu   | 0xFFFFFFFB                  | 寄存器初始化负数(符号扩展)
#  0x000010 |  add     | 0x0000001E                  | 寄存器加法 (20 + 10 = 30)
#  0x000014 |  addu    | 0x0000000F                  | 无符号加法 (20 + -5 = 15)
#  0x000018 |  addi    | 0xFFFFFFFB                  | 立即数加法 (10 + -15 = -5)
#  0x00001C |  sub     | 0x0000000A                  | 减法 (20 - 10 = 10)
#  0x000020 |  and     | 0x00000000                  | 逻辑与 (0x5555 & 0xaaaa)
#  0x000024 |  andi    | 0x00000055                  | 立即数与 (零扩展验证)
#  0x000028 |  or      | 0x0000FFFF                  | 逻辑或 (0x5555 | 0xaaaa)
#  0x00002C |  ori     | 0x0000FF55                  | 立即数或 (零扩展验证)
#  0x000030 |  nor     | 0xFFFFFFFF                  | 逻辑或非 (!(0|0))
#  0x000034 |  sll     | 0x00000008                  | 逻辑左移 (2 << 2 = 8)
#  0x000038 |  srl     | 0x00000004                  | 逻辑右移 (8 >>> 1 = 4)
#  0x00003C |  sra     | 0xFFFFFFFE                  | 算术右移 (负数高位补1验证)
#  0x000040 |  slt     | 0x00000001                  | 有符号比较 (-5 < 10 成立)
#  0x000044 |  sltu    | 0x00000000                  | 无符号比较 (大数 < 小数不成立)
#  0x000048 |  slti    | 0x00000001                  | 立即数比较 (-5 < 0 成立)
#  0x00004C |  jal/jr  | 0x00000063                  | 控制流全通标记 (0x63 = 99)
# ====================================================================

.data
    test_data: .word 0x12345678, 0xabcdef01, 0x00000000

.text
.globl main
main:
    # 建立 RAM 的基地址指针，令 $gp = 0x00000000
    addiu $gp, $0, 0        

    # ----------------------------------------------------------------
    # 1. 初始化与立即数加法 (测试指令 10: addiu)
    # ----------------------------------------------------------------
    addiu $s0, $0, 10       
    sw    $s0, 8($gp)       # 落盘验证 -> RAM[0x08] = 0x0000000A
    
    addiu $s1, $0, 20       
    
    addiu $s2, $0, -5       
    sw    $s2, 12($gp)      # 落盘验证 -> RAM[0x0C] = 0xFFFFFFFB (负数符号扩展)

    # ----------------------------------------------------------------
    # 2. 算术运算指令测试 (测试指令 1: add, 9: addu, 3: addi, 16: sub)
    # ----------------------------------------------------------------
    add   $t0, $s1, $s0     
    sw    $t0, 16($gp)      # 落盘验证 -> RAM[0x10] = 0x0000001E (30)

    addu  $t1, $s1, $s2     
    sw    $t1, 20($gp)      # 落盘验证 -> RAM[0x14] = 0x0000000F (15)

    addi  $t2, $s0, -15     
    sw    $t2, 24($gp)      # 落盘验证 -> RAM[0x18] = 0xFFFFFFFB (-5)

    sub   $t3, $s1, $s0     
    sw    $t3, 28($gp)      # 落盘验证 -> RAM[0x1C] = 0x0000000A (10)

    # ----------------------------------------------------------------
    # 3. 逻辑运算指令测试 (测试指令 11: and, 12: andi, 17: or, 18: ori, 19: nor)
    # ----------------------------------------------------------------
    addiu $s3, $0, 0x5555   
    addiu $s4, $0, 0xaaaa   
    
    and   $t4, $s3, $s4     
    sw    $t4, 32($gp)      # 落盘验证 -> RAM[0x20] = 0x00000000

    andi  $t5, $s3, 0x00ff  
    sw    $t5, 36($gp)      # 落盘验证 -> RAM[0x24] = 0x00000055 (零扩展)

    or    $t6, $s3, $s4     
    sw    $t6, 40($gp)      # 落盘验证 -> RAM[0x28] = 0x0000FFFF

    ori   $t7, $s3, 0xff00  
    sw    $t7, 44($gp)      # 落盘验证 -> RAM[0x2C] = 0x0000FF55 (零扩展)

    nor   $t8, $t4, $0      
    sw    $t8, 48($gp)      # 落盘验证 -> RAM[0x30] = 0xFFFFFFFF

    # ----------------------------------------------------------------
    # 4. 移位运算指令测试 (测试指令 13: sll, 14: srl, 15: sra)
    # ----------------------------------------------------------------
    addiu $s5, $0, 2        
    sll   $t0, $s5, 2       
    sw    $t0, 52($gp)      # 落盘验证 -> RAM[0x34] = 0x00000008

    srl   $t1, $t0, 1       
    sw    $t1, 56($gp)      # 落盘验证 -> RAM[0x38] = 0x00000004
    
    sra   $t2, $s2, 2       # $s2 是 -5 (0xfffffffb)
    sw    $t2, 60($gp)      # 落盘验证 -> RAM[0x3C] = 0xFFFFFFFE (-2, 算术右移符号保持)

    # ----------------------------------------------------------------
    # 5. 比较置位指令测试 (测试指令 2: slt, 20: sltu, 21: slti)
    # ----------------------------------------------------------------
    slt   $t3, $s2, $s0     # -5 < 10 成立
    sw    $t3, 64($gp)      # 落盘验证 -> RAM[0x40] = 0x00000001

    sltu  $t4, $s2, $s0     # 无符号 0xfffffffb < 0x0000000a 不成立
    sw    $t4, 68($gp)      # 落盘验证 -> RAM[0x44] = 0x00000000

    slti  $t5, $s2, 0       # -5 < 0 成立
    sw    $t5, 72($gp)      # 落盘验证 -> RAM[0x48] = 0x00000001

    # ----------------------------------------------------------------
    # 6. 访存与分支跳转组合验证 (测试指令 4: lw, 6: beq, 7: bne, 22: j, 23: jal, 24: jr)
    # ----------------------------------------------------------------
    # 重新用 lw 读取最初的 RAM 数据来做分支判断，顺便测试 lw 指令
    lw    $a0, 0($gp)       # $a0 = 0x12345678
    lw    $a1, 0($gp)       # $a1 = 0x12345678
    addiu $a2, $0, 0        # $a2 = 0

    beq   $a0, $a1, test_bne # 如果 lw 和 beq 正常，必跳转
    beq   $0, $0, error      # 没跳走说明出错，卡死

test_bne:
    bne   $a0, $a2, test_j   # 如果 bne 正常，必跳转
    beq   $0, $0, error

test_j:
    j     test_jal           # 如果 j 正常，必跳转
    beq   $0, $0, error

test_jal:
    jal   target_sub         # 调用子程序，测试 jal
    
    # 子程序成功返回后到这里
    addiu $v1, $0, 99        # 终极全通标记 99 (0x63)
    sw    $v1, 76($gp)      # 落盘验证 -> RAM[0x4C] = 0x00000063
    j     finish

target_sub:
    jr    $ra                # 测试 jr 返回

# ----------------------------------------------------------------
# 7. 终点与错误陷阱 (测试指令 8: syscall)
# ----------------------------------------------------------------
finish:
    addiu $v0, $0, 10       
    syscall                 # 顺利停机！

error:
    # 任何一步跳转失败，或者逻辑算错导致分支走错，都会死锁在这里。
    # 此时 RAM[0x4C] 将永远是初始的 0x00000000，不会变成 0x63。
    beq   $0, $0, error